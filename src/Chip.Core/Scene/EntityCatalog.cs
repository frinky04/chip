using System.Numerics;
using System.Text.Json;

namespace Chip.Core.Scene;

public enum PropType { Bool, Int, Float, String, Enum, Color, Vector2, Vector3, Node, Resource, Unsupported }

public sealed record EnumOption(string Label, JsonElement Value);

/// <summary>One property of an entity class, as the engine declares it (a Godot <c>@export</c> var).</summary>
public sealed record PropSpec
{
    public required string Name { get; init; }
    public required PropType Type { get; init; }
    /// <summary>The value when the entity doesn't set one (<see cref="EntityValues.Null"/> for none).</summary>
    public JsonElement Default { get; init; } = EntityValues.Null;
    public string Doc { get; init; } = "";
    /// <summary>The engine's group heading ("Sound"), empty for none.</summary>
    public string Group { get; init; } = "";
    /// <summary>Slider range and step from a range hint. Values past the range are allowed when the matching Or flag is set.</summary>
    public (double Min, double Max, double Step)? Range { get; init; }
    public bool OrGreater { get; init; }
    public bool OrLess { get; init; }
    public string Suffix { get; init; } = "";
    public IReadOnlyList<EnumOption> Options { get; init; } = [];
    /// <summary>Node or resource class (<c>Node3D</c>, <c>Material</c>), when the engine restricts it.</summary>
    public string? Class { get; init; }
    /// <summary>Whole-number vector components.</summary>
    public bool Integer { get; init; }
    /// <summary>The engine type of an <see cref="PropType.Unsupported"/> property (<c>Array</c>).</summary>
    public string? EngineType { get; init; }

    /// <summary>"open_angle" → "Open angle".</summary>
    public string Label => EntityClass.Humanize(Name);
}

/// <summary>
/// An entity class: a scene in the engine project (or Chip's own <see cref="ReferenceModels.ClassName"/>), its properties
/// and the box drawn and picked around the origin (entity space, metres).
/// </summary>
public sealed class EntityClass
{
    public required string Name { get; init; }
    public required string Label { get; init; }
    public string Doc { get; init; } = "";
    /// <summary>The engine scene (<c>res://entities/door.tscn</c>) and its stable id (<c>uid://…</c>), when known.</summary>
    public string? Scene { get; init; }
    public string? Uid { get; init; }
    /// <summary>The scene root's engine type (<c>OmniLight3D</c>).</summary>
    public string Base { get; init; } = "";
    public Vector3 BoxMin { get; init; } = new(-0.2f);
    public Vector3 BoxMax { get; init; } = new(0.2f);
    /// <summary>Absolute path of a .glb showing the scene's meshes, drawn in place of the box.</summary>
    public string? Preview { get; init; }
    public IReadOnlyList<PropSpec> Props { get; init; } = [];
    /// <summary>False for a class name the catalog doesn't define (a level from another project, or a deleted scene).</summary>
    public bool Known { get; init; } = true;
    /// <summary>Chip's own classes that never reach the engine as such (reference models).</summary>
    public bool EditorOnly { get; init; }

    /// <summary>The doc's first line, cut to about a sentence's length, for lists and the inspector (the full doc is a tooltip).</summary>
    public string Summary => _summary ??= Summarize(Doc, 160);

    Dictionary<string, PropSpec>? _byName;
    string? _summary;

    /// <summary>
    /// The first line of <paramref name="doc"/>, cut at a word before <paramref name="max"/> characters with "…". A first
    /// line ending in ":" (a list follows) also gets "…" in place of the colon.
    /// </summary>
    public static string Summarize(string doc, int max)
    {
        int nl = doc.IndexOf('\n');
        var line = (nl >= 0 ? doc[..nl] : doc).Trim();
        if (line.Length > max)
        {
            int cut = line.LastIndexOf(' ', max);
            return line[..(cut > max / 2 ? cut : max)].TrimEnd(' ', ',', ';', ':', '.') + "…";
        }
        return nl >= 0 && line.EndsWith(':') ? line[..^1].TrimEnd() + "…" : line;
    }

    public PropSpec? Prop(string name) =>
        (_byName ??= Props.GroupBy(p => p.Name).ToDictionary(g => g.Key, g => g.First())).GetValueOrDefault(name);

    /// <summary>"info_player_start" → "Info player start".</summary>
    public static string Humanize(string name)
    {
        var words = name[(name.LastIndexOf('/') + 1)..].Replace('_', ' ').Trim();
        return words.Length == 0 ? name : char.ToUpperInvariant(words[0]) + words[1..];
    }
}

/// <summary>
/// The entity classes a level can use. A Godot project's come from the manifest the Chip import addon writes
/// (<c>.chip/entities.json</c>, see <c>docs/entities.md</c>); without one, Chip offers the addon's built-in classes
/// (embedded from <c>BuiltinEntities.json</c>, generated by the addon). Reference models are added to every catalog.
/// </summary>
public sealed class EntityCatalog
{
    public const int ManifestVersion = 1;

    readonly Dictionary<string, EntityClass> _byName;

    public IReadOnlyList<EntityClass> Classes { get; }
    /// <summary>The manifest this came from; null for the built-in catalog.</summary>
    public string? Source { get; }

    EntityCatalog(IEnumerable<EntityClass> classes, string? source)
    {
        Classes = classes.Append(ReferenceModels.Class).ToList();
        _byName = Classes.ToDictionary(c => c.Name, StringComparer.Ordinal);
        Source = source;
    }

    public EntityClass? Find(string name) => _byName.GetValueOrDefault(name);

    public static EntityCatalog BuiltIn { get; } = LoadBuiltIn();

    static EntityCatalog LoadBuiltIn()
    {
        using var stream = typeof(EntityCatalog).Assembly.GetManifestResourceStream("Chip.Core.BuiltinEntities.json")
            ?? throw new InvalidOperationException("BuiltinEntities.json isn't embedded in Chip.Core");
        using var reader = new StreamReader(stream);
        return Parse(reader.ReadToEnd(), null);
    }

    /// <summary>
    /// Reads a manifest. Preview paths resolve against the manifest's folder (<paramref name="manifestPath"/>; previews are
    /// dropped when it's null). Throws <see cref="InvalidDataException"/> with what's wrong.
    /// </summary>
    public static EntityCatalog Parse(string json, string? manifestPath)
    {
        JsonDocument doc;
        try { doc = JsonDocument.Parse(json); }
        catch (JsonException e) { throw new InvalidDataException($"isn't valid JSON: {e.Message}"); }
        using (doc)
        {
            var root = doc.RootElement;
            if (root.ValueKind != JsonValueKind.Object || !root.TryGetProperty("classes", out var classes) || classes.ValueKind != JsonValueKind.Object)
                throw new InvalidDataException("has no \"classes\" object");
            if (root.TryGetProperty("version", out var v) && v.ValueKind == JsonValueKind.Number && v.GetInt32() > ManifestVersion)
                throw new InvalidDataException($"is version {v.GetInt32()}, newer than this Chip reads ({ManifestVersion}). Update Chip");
            var dir = manifestPath != null ? Path.GetDirectoryName(Path.GetFullPath(manifestPath)) : null;
            var list = new List<EntityClass>();
            foreach (var c in classes.EnumerateObject())
            {
                if (c.Name == ReferenceModels.ClassName) continue; // Chip's own
                list.Add(ParseClass(c.Name, c.Value, dir));
            }
            return new EntityCatalog(list, manifestPath);
        }
    }

    static EntityClass ParseClass(string name, JsonElement c, string? dir)
    {
        if (c.ValueKind != JsonValueKind.Object) throw new InvalidDataException($"class {name} isn't an object");
        var props = new List<PropSpec>();
        if (c.TryGetProperty("props", out var ps) && ps.ValueKind == JsonValueKind.Array)
            foreach (var p in ps.EnumerateArray()) props.Add(ParseProp(name, p));
        Vector3 min = new(-0.2f), max = new(0.2f);
        if (c.TryGetProperty("bounds", out var b) && b.ValueKind == JsonValueKind.Array && b.GetArrayLength() == 2
            && EntityValues.Vector(b[0], 3) is { } lo && EntityValues.Vector(b[1], 3) is { } hi)
        {
            min = new Vector3(lo[0], lo[1], lo[2]);
            max = new Vector3(hi[0], hi[1], hi[2]);
        }
        string? preview = Str(c, "preview") is { Length: > 0 } rel && dir != null ? Path.GetFullPath(Path.Combine(dir, rel)) : null;
        return new EntityClass
        {
            Name = name, Label = Str(c, "label") ?? EntityClass.Humanize(name), Doc = Str(c, "doc") ?? "",
            Scene = Str(c, "scene"), Uid = Str(c, "uid"), Base = Str(c, "base") ?? "",
            BoxMin = min, BoxMax = max, Preview = preview, Props = props,
        };
    }

    static PropSpec ParseProp(string cls, JsonElement p)
    {
        if (Str(p, "name") is not { Length: > 0 } name) throw new InvalidDataException($"class {cls} has a property without a name");
        var type = Str(p, "type") switch
        {
            "bool" => PropType.Bool, "int" => PropType.Int, "float" => PropType.Float, "string" => PropType.String,
            "enum" => PropType.Enum, "color" => PropType.Color, "vector2" => PropType.Vector2, "vector3" => PropType.Vector3,
            "node" => PropType.Node, "resource" => PropType.Resource, _ => PropType.Unsupported,
        };
        var options = new List<EnumOption>();
        if (p.TryGetProperty("options", out var os) && os.ValueKind == JsonValueKind.Array)
            foreach (var o in os.EnumerateArray())
                if (o.ValueKind == JsonValueKind.Object && o.TryGetProperty("value", out var ov))
                    options.Add(new EnumOption(Str(o, "label") ?? EntityValues.Text(ov), ov.Clone()));
        (double, double, double)? range = null;
        if (p.TryGetProperty("range", out var r) && r.ValueKind == JsonValueKind.Array && r.GetArrayLength() >= 2
            && r[0].ValueKind == JsonValueKind.Number && r[1].ValueKind == JsonValueKind.Number)
            range = (r[0].GetDouble(), r[1].GetDouble(), r.GetArrayLength() > 2 && r[2].ValueKind == JsonValueKind.Number ? r[2].GetDouble() : 0);
        var spec = new PropSpec
        {
            Name = name, Type = type, Doc = Str(p, "doc") ?? "", Group = Str(p, "group") ?? "",
            Range = range, OrGreater = Flag(p, "or_greater"), OrLess = Flag(p, "or_less"), Suffix = Str(p, "suffix") ?? "",
            Options = options, Class = Str(p, "class"), Integer = Flag(p, "integer"),
            EngineType = type == PropType.Unsupported ? Str(p, "godot") ?? Str(p, "type") : null,
            Default = p.TryGetProperty("default", out var d) ? d.Clone() : EntityValues.Null,
        };
        // Normalised to the type; a default it can't read (a hand-edited manifest) becomes "none".
        return spec with { Default = EntityValues.Coerce(spec, spec.Default, out _) ?? EntityValues.Null };
    }

    static string? Str(JsonElement o, string key) =>
        o.TryGetProperty(key, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() : null;

    static bool Flag(JsonElement o, string key) => o.TryGetProperty(key, out var v) && v.ValueKind == JsonValueKind.True;
}
